import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';
const source = await readFile('src/lib/markdown/links.ts', 'utf8');
const { code } = await transform(source, { loader: 'ts', format: 'esm' });
const { resolveTarget } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const notes = ['a/Target.md', 'b/Target.md', 'Root.md', 'folder/Space Name.md', 'folder/Hash#Name.md', 'folder/Long.markdown'].map(path => ({ path, title: 'Heading differs from filename', aliases: path === 'Root.md' ? ['别名'] : [] }));
const resolved = (target, sourcePath, expected) => assert.deepEqual(resolveTarget(target, notes, sourcePath), { path: expected, ambiguous: false }, `${sourcePath}: ${target}`);
resolved('Target', 'b/Source.md', 'b/Target.md');
resolved('./Target.md', 'b/Source.md', 'b/Target.md');
resolved('../a/Target', 'b/Source.md', 'a/Target.md');
resolved('/a/Target', 'b/Source.md', 'a/Target.md');
resolved('别名', 'b/Source.md', 'Root.md');
resolved('folder/Space%20Name.md', 'Source.md', 'folder/Space Name.md');
resolved('folder/Hash%23Name.md', 'Source.md', 'folder/Hash#Name.md');
resolved('Long.markdown', 'folder/Source.md', 'folder/Long.markdown');
resolved('../../a/Target', 'Source.md', null);
resolved('https://example.com/Root.md', 'Source.md', null);
resolved('./Target', 'missing/Source.md', null);
assert.deepEqual(resolveTarget('Target', notes, 'other/Source.md'), { path: null, ambiguous: true });
assert.deepEqual(resolveTarget('Target', [...notes].reverse(), 'other/Source.md'), { path: null, ambiguous: true });
console.log('PASS graph target paths, aliases, same-folder resolution and stable ambiguity');
